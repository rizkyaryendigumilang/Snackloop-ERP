-- =========================================================================
-- SNACKLOOP ERP - SUPABASE / POSTGRESQL ROW LEVEL SECURITY (RLS) POLICIES
-- =========================================================================
-- Skrip ini mengaktifkan dan mengonfigurasi Row Level Security (RLS) di PostgreSQL / Supabase
-- untuk melindungi semua tabel operasional dari manipulasi data tidak sah, pembocoran kredensial,
-- dan akses liar via PostgREST anon client.
--
-- FITUR KEAMANAN:
-- 1. Idempoten & Aman: Otomatis mendeteksi dan membuat tabel operasional jika belum ada (CREATE TABLE IF NOT EXISTS)
--    sehingga tidak akan pernah gagal dengan error 'relation does not exist'.
-- 2. Mengaktifkan Row Level Security (RLS) pada seluruh 12 tabel operasional.
-- 3. Proteksi Kredensial Pengguna (SEC-001 & SEC-002): Menolak pendaftaran akun admin liar via REST.
-- 4. Immutable Audit Trail: Tabel audit_logs hanya boleh dibaca dan disisipkan (anti manipulasi riwayat).
--
-- CARA MENJALANKAN DI SUPABASE:
-- 1. Buka Supabase Dashboard > Pilih Proyek SnackLoop ERP
-- 2. Masuk ke menu "SQL Editor"
-- 3. Paste seluruh skrip di bawah ini dan klik "Run"
-- =========================================================================

-- -------------------------------------------------------------------------
-- 0. PASTIKAN SELURUH TABEL OPERASIONAL TERSEDIA (IDEMPOTENT SCHEMA DEFINITION)
-- -------------------------------------------------------------------------
